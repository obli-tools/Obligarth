import type { Knex } from 'knex';

// =============================================================================
// Apple integration, part 2: push certificates, ADE servers, Apps and Books, translatable live alerts
// (docs: integration-apple-edge §4.3, §11, §12)
// =============================================================================
//   - tenant_apple_push: the push certificate workflow and its history (the key lives in apple-edge);
//   - tenant_apple_ade_tokens: mirror of the ADE servers (tokens and keys live in apple-edge);
//   - tenant_apple_vpp_tokens: Apps and Books content tokens, sealed in the brain's vault (FND-03);
//   - vpp_assets, vpp_assignments, vpp_operations, vpp_notifications_inbox: licences, asynchronous
//     operations and notifications received;
//   - live_alerts gains kind, i18n_key and i18n_params (I11): catalogue kind and translatable text.
// Same columns, types, constraints and names as the specification, written in SQL like the migrations of
// lot A; tenant_id defaults to the context's tenant (rls-tenant §5.4, rule 5); every reference between
// tenant tables is a composite key (tenant_id, x) named <table>_<column>_tenant_fk. Runs as obligarth_owner
// (server-migrate), after apple_tenants; ends with obligarth.rls_assert_clean(). No question mark in the SQL
// (knex.raw would bind it); kept verbatim by String.raw.

// coffre-secrets §4.1: v1:<DEK uuid>:<iv>:<ct>:<tag>
const SEALED_RE =
  '^v1:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}:[A-Za-z0-9_-]{16}:[A-Za-z0-9_-]*:[A-Za-z0-9_-]{22}$';
const PUSH_PURPOSES = ['initial', 'renewal', 'topic_change', 'import'];
const PUSH_STATES = ['vendor_signature_pending', 'apple_upload_pending', 'active', 'legacy', 'superseded',
  'expired', 'revoked', 'abandoned'];
const ADE_STATES = ['awaiting_token', 'active', 'terms_not_signed', 'expired', 'error', 'removed'];
const VPP_STATES = ['active', 'foreign_mdm', 'expired', 'invalid', 'removed'];
const VPP_ASSIGNMENT_STATES = ['associated', 'associating', 'disassociating', 'failed'];
const VPP_OPERATION_KINDS = ['associate', 'disassociate', 'revoke', 'users_create', 'users_update', 'users_retire'];
const VPP_OPERATION_STATES = ['requested', 'pending', 'complete', 'failed', 'abandoned'];

const list = (values: readonly string[]): string => values.map((v) => `'${v}'`).join(', ');

const UP = String.raw`-- =============================================================================
-- Apple integration, part 2: push, ADE, Apps and Books, live alert texts (run as obligarth_owner)
-- =============================================================================
SET LOCAL search_path = pg_catalog, pg_temp;

DO $$
BEGIN
  IF to_regprocedure('obligarth_private.rls_apply(regclass, text, text)') IS NULL
     OR to_regclass('obligarth.tenant_apple_edge') IS NULL THEN
    RAISE EXCEPTION 'apple_integrations: apply the RLS migrations and apple_tenants first';
  END IF;
END $$;

-- ── Push certificates: workflow and history ─────────────────────────────────
CREATE TABLE obligarth.tenant_apple_push (
  id                  uuid          NOT NULL,              -- generated by the server
  tenant_id           integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  edge_cert_id        uuid,                                -- apple_edge.push_certs.id
  purpose             varchar(16)   NOT NULL,
  state               varchar(32)   NOT NULL,
  state_at            timestamptz   NOT NULL,
  csr_der_b64         text,                                -- public CSR (base64 DER)
  vendor_request_b64  text,                                -- signed request for identity.apple.com (public)
  topic               varchar(255),
  cert_sha256         varchar(64),
  not_after           timestamptz,
  pending_cert_pem    text,                                -- public certificate awaiting a topic-change approval
  apple_account_hint  varchar(200),                        -- service Managed Apple Account: a hint, never a password
  owner_contact       varchar(200),
  approval_id         integer,                             -- pending_approvals.id (topic change)
  created_by          integer,
  vendor_signed_at    timestamptz,
  activated_at        timestamptz,
  closed_at           timestamptz,
  created_at          timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT tenant_apple_push_pkey PRIMARY KEY (id),
  CONSTRAINT tenant_apple_push_tenant_id_id_unique UNIQUE (tenant_id, id),
  CONSTRAINT tenant_apple_push_tenant_id_foreign FOREIGN KEY (tenant_id)
    REFERENCES obligarth.tenants (id) ON DELETE CASCADE,
  CONSTRAINT tenant_apple_push_created_by_foreign FOREIGN KEY (created_by)
    REFERENCES obligarth.users (id) ON DELETE SET NULL,
  CONSTRAINT tenant_apple_push_purpose_check CHECK (purpose IN (${list(PUSH_PURPOSES)})),
  CONSTRAINT tenant_apple_push_state_check CHECK (state IN (${list(PUSH_STATES)})),
  CONSTRAINT tenant_apple_push_topic_check CHECK (topic IS NULL OR topic LIKE 'com.apple.mgmt.%'),
  CONSTRAINT tenant_apple_push_cert_sha256_check CHECK (cert_sha256 IS NULL OR cert_sha256 ~ '^[0-9a-f]{64}$')
);
CREATE UNIQUE INDEX tenant_apple_push_one_open ON obligarth.tenant_apple_push (tenant_id)
  WHERE state IN ('vendor_signature_pending', 'apple_upload_pending');
CREATE UNIQUE INDEX tenant_apple_push_one_active ON obligarth.tenant_apple_push (tenant_id)
  WHERE state = 'active';
SELECT obligarth_private.rls_apply('obligarth.tenant_apple_push', 'tenant');

-- ── ADE servers (mirror; tokens and keys live in apple-edge) ─────────────────
CREATE TABLE obligarth.tenant_apple_ade_tokens (
  id                      uuid          NOT NULL,          -- = apple_edge.ade_tokens.id
  tenant_id               integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  label                   varchar(100)  NOT NULL,
  state                   varchar(24)   NOT NULL,
  state_at                timestamptz   NOT NULL,
  public_certificate_pem  text          NOT NULL,          -- to upload into Apple Business (public)
  server_name             varchar(200),
  server_uuid             varchar(64),
  not_after               timestamptz,
  apple_account_hint      varchar(200),
  last_sync_at            timestamptz,
  last_fetch_at           timestamptz,
  consecutive_errors      integer       NOT NULL DEFAULT 0,
  last_error_code         varchar(64),
  byod_discovery          boolean       NOT NULL DEFAULT false,
  byod_discovery_at       timestamptz,
  created_by              integer,
  created_at              timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at              timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  removed_at              timestamptz,
  CONSTRAINT tenant_apple_ade_tokens_pkey PRIMARY KEY (id),
  CONSTRAINT tenant_apple_ade_tokens_tenant_id_id_unique UNIQUE (tenant_id, id),
  CONSTRAINT tenant_apple_ade_tokens_tenant_id_foreign FOREIGN KEY (tenant_id)
    REFERENCES obligarth.tenants (id) ON DELETE CASCADE,
  CONSTRAINT tenant_apple_ade_tokens_created_by_foreign FOREIGN KEY (created_by)
    REFERENCES obligarth.users (id) ON DELETE SET NULL,
  CONSTRAINT tenant_apple_ade_tokens_state_check CHECK (state IN (${list(ADE_STATES)}))
);
SELECT obligarth_private.rls_apply('obligarth.tenant_apple_ade_tokens', 'tenant');

-- ── Apps and Books content tokens (sealed in the brain's vault) ──────────────
CREATE TABLE obligarth.tenant_apple_vpp_tokens (
  id                        uuid          NOT NULL,
  tenant_id                 integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  label                     varchar(100)  NOT NULL,
  org_name                  varchar(200),                  -- orgName of the token file
  location_name             varchar(200),                  -- organizational unit (client/config)
  location_uid              varchar(64),
  s_token_enc               text          NOT NULL,        -- vault seal (FND-03)
  s_token_sha256            varchar(64)   NOT NULL,        -- duplicate detection without opening
  exp_date                  timestamptz   NOT NULL,
  state                     varchar(16)   NOT NULL,
  state_at                  timestamptz   NOT NULL,
  mdm_info_id               varchar(128)  NOT NULL,        -- what we write into client/config
  notification_ref          varchar(32)   NOT NULL,        -- path segment of the notification URL
  notification_secret_hash  varchar(64)   NOT NULL,        -- SHA-256 of the bearer Apple presents
  test_notification_at      timestamptz,
  last_notification_at      timestamptz,
  assets_version_id         varchar(64),                   -- Apple's versionId (sinceVersionId)
  assignments_version_id    varchar(64),
  last_sync_at              timestamptz,
  consecutive_errors        integer       NOT NULL DEFAULT 0,
  last_error_code           varchar(64),
  apple_account_hint        varchar(200),
  created_by                integer,
  created_at                timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  removed_at                timestamptz,
  CONSTRAINT tenant_apple_vpp_tokens_pkey PRIMARY KEY (id),
  CONSTRAINT tenant_apple_vpp_tokens_tenant_id_id_unique UNIQUE (tenant_id, id),
  CONSTRAINT tenant_apple_vpp_tokens_tenant_id_foreign FOREIGN KEY (tenant_id)
    REFERENCES obligarth.tenants (id) ON DELETE CASCADE,
  CONSTRAINT tenant_apple_vpp_tokens_created_by_foreign FOREIGN KEY (created_by)
    REFERENCES obligarth.users (id) ON DELETE SET NULL,
  CONSTRAINT tenant_apple_vpp_tokens_state_check CHECK (state IN (${list(VPP_STATES)})),
  CONSTRAINT tenant_apple_vpp_tokens_s_token_enc_sealed CHECK (s_token_enc ~ '${SEALED_RE}')
);
CREATE UNIQUE INDEX tenant_apple_vpp_tokens_ref ON obligarth.tenant_apple_vpp_tokens (notification_ref);
-- one live tenant per content token, instance-wide
CREATE UNIQUE INDEX tenant_apple_vpp_tokens_live ON obligarth.tenant_apple_vpp_tokens (s_token_sha256)
  WHERE state <> 'removed';
SELECT obligarth_private.rls_apply('obligarth.tenant_apple_vpp_tokens', 'tenant');

CREATE TABLE obligarth.vpp_assets (
  id                  bigserial     NOT NULL,
  tenant_id           integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  vpp_token_id        uuid          NOT NULL,
  adam_id             varchar(32)   NOT NULL,
  pricing_param       varchar(8)    NOT NULL,              -- STDQ | PLUS
  product_type        varchar(16)   NOT NULL,              -- App | Book | Mac…
  device_assignable   boolean       NOT NULL,
  revocable           boolean       NOT NULL,
  supported_platforms jsonb         NOT NULL DEFAULT '[]',
  total_count         integer       NOT NULL,
  assigned_count      integer       NOT NULL,
  available_count     integer       NOT NULL,
  retired_count       integer       NOT NULL,
  updated_at          timestamptz   NOT NULL,
  CONSTRAINT vpp_assets_pkey PRIMARY KEY (id),
  CONSTRAINT vpp_assets_tenant_id_vpp_token_id_adam_id_pricing_param_unique UNIQUE (tenant_id, vpp_token_id, adam_id, pricing_param),
  CONSTRAINT vpp_assets_vpp_token_id_tenant_fk FOREIGN KEY (tenant_id, vpp_token_id)
    REFERENCES obligarth.tenant_apple_vpp_tokens (tenant_id, id) ON DELETE CASCADE
);
SELECT obligarth_private.rls_apply('obligarth.vpp_assets', 'tenant');

CREATE TABLE obligarth.vpp_assignments (
  id                    bigserial     NOT NULL,
  tenant_id             integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  vpp_token_id          uuid          NOT NULL,
  adam_id               varchar(32)   NOT NULL,
  pricing_param         varchar(8)    NOT NULL,
  serial_number         varchar(64),                       -- device licence
  client_user_id        varchar(64),                       -- user licence (BYOD)
  device_id             integer,
  state                 varchar(24)   NOT NULL,
  pending_operation_id  uuid,
  updated_at            timestamptz   NOT NULL,
  CONSTRAINT vpp_assignments_pkey PRIMARY KEY (id),
  CONSTRAINT vpp_assignments_state_check CHECK (state IN (${list(VPP_ASSIGNMENT_STATES)})),
  CONSTRAINT vpp_assignments_target_check CHECK ((serial_number IS NULL) <> (client_user_id IS NULL)),
  CONSTRAINT vpp_assignments_vpp_token_id_tenant_fk FOREIGN KEY (tenant_id, vpp_token_id)
    REFERENCES obligarth.tenant_apple_vpp_tokens (tenant_id, id) ON DELETE CASCADE,
  CONSTRAINT vpp_assignments_device_id_tenant_fk FOREIGN KEY (tenant_id, device_id)
    REFERENCES obligarth.devices (tenant_id, id) ON DELETE SET NULL (device_id)
);
CREATE UNIQUE INDEX vpp_assignments_unique ON obligarth.vpp_assignments
  (tenant_id, vpp_token_id, adam_id, pricing_param, (coalesce(serial_number, '')), (coalesce(client_user_id, '')));
SELECT obligarth_private.rls_apply('obligarth.vpp_assignments', 'tenant');

CREATE TABLE obligarth.vpp_operations (
  id                uuid          NOT NULL,
  tenant_id         integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  vpp_token_id      uuid          NOT NULL,
  event_id          varchar(64),                           -- Apple's eventId, once the API answered
  kind              varchar(24)   NOT NULL,
  state             varchar(16)   NOT NULL,
  request           jsonb         NOT NULL,                -- adamIds, serialNumbers, clientUserIds; never a token
  result_summary    jsonb,
  requested_by_ref  varchar(100),                          -- 'mdm_command:<uuid>', 'user:<id>', 'job:<queue>'
  status_polls      integer       NOT NULL DEFAULT 0,
  created_at        timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at      timestamptz,
  CONSTRAINT vpp_operations_pkey PRIMARY KEY (id),
  CONSTRAINT vpp_operations_kind_check CHECK (kind IN (${list(VPP_OPERATION_KINDS)})),
  CONSTRAINT vpp_operations_state_check CHECK (state IN (${list(VPP_OPERATION_STATES)})),
  CONSTRAINT vpp_operations_vpp_token_id_tenant_fk FOREIGN KEY (tenant_id, vpp_token_id)
    REFERENCES obligarth.tenant_apple_vpp_tokens (tenant_id, id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX vpp_operations_event ON obligarth.vpp_operations (vpp_token_id, event_id)
  WHERE event_id IS NOT NULL;
SELECT obligarth_private.rls_apply('obligarth.vpp_operations', 'tenant');

CREATE TABLE obligarth.vpp_notifications_inbox (
  id                 uuid          NOT NULL,
  tenant_id          integer       NOT NULL DEFAULT obligarth.ctx_tenant(),
  vpp_token_id       uuid          NOT NULL,
  notification_type  varchar(32)   NOT NULL,
  notification_id    varchar(128),                         -- Apple's id when present (deduplication)
  payload            jsonb         NOT NULL,               -- 1 MiB at most
  attempts           integer       NOT NULL DEFAULT 0,
  last_error_code    varchar(64),
  received_at        timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed_at       timestamptz,
  CONSTRAINT vpp_notifications_inbox_pkey PRIMARY KEY (id),
  CONSTRAINT vpp_notifications_inbox_vpp_token_id_tenant_fk FOREIGN KEY (tenant_id, vpp_token_id)
    REFERENCES obligarth.tenant_apple_vpp_tokens (tenant_id, id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX vpp_notifications_inbox_dedup ON obligarth.vpp_notifications_inbox
  (vpp_token_id, notification_id) WHERE notification_id IS NOT NULL;
SELECT obligarth_private.rls_apply('obligarth.vpp_notifications_inbox', 'tenant');

-- ── Live alerts: catalogue kind and translatable texts (I11) ─────────────────
ALTER TABLE obligarth.live_alerts
  ADD COLUMN kind        varchar(64),                      -- section 12.1; NULL for the core's own alerts
  ADD COLUMN i18n_key    varchar(100),
  ADD COLUMN i18n_params jsonb;                            -- scalars only, never personal data

SELECT obligarth.rls_assert_clean();
`;

